//! SQLite persistence for chats and their messages.

use std::time::{SystemTime, UNIX_EPOCH};

use rusqlite::{Connection, Result, params};

use super::{Message, Role};
use crate::storage;

const SCHEMA: &str = "
CREATE TABLE IF NOT EXISTS chats (
    id          INTEGER PRIMARY KEY,
    title       TEXT    NOT NULL,
    -- 1 until the user renames the chat; only auto-titled chats get AI titles.
    auto_titled INTEGER NOT NULL DEFAULT 1,
    created_at  INTEGER NOT NULL,
    updated_at  INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS chat_messages (
    id         INTEGER PRIMARY KEY,
    chat_id    INTEGER NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    role       TEXT    NOT NULL,
    content    TEXT    NOT NULL,
    created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS chat_messages_by_chat ON chat_messages(chat_id, id);
";

pub struct ChatSummary {
    pub id: i64,
    pub title: String,
}

pub struct Store {
    conn: Connection,
}

impl Store {
    /// Opens the on-disk database. If that fails, falls back to an in-memory
    /// one so the chat still works, and returns a warning to show the user.
    pub fn open() -> (Self, Option<String>) {
        let on_disk = storage::open_db().and_then(|conn| {
            conn.execute_batch(SCHEMA).map_err(|e| e.to_string())?;
            Ok(conn)
        });
        match on_disk {
            Ok(conn) => (Self { conn }, None),
            Err(err) => {
                let conn = Connection::open_in_memory().expect("in-memory SQLite always opens");
                conn.execute_batch(SCHEMA).expect("schema is valid");
                (Self { conn }, Some(format!("Chats won't be saved: {err}")))
            }
        }
    }

    /// All chats, most recently active first.
    pub fn chats(&self) -> Result<Vec<ChatSummary>> {
        let mut stmt = self
            .conn
            .prepare("SELECT id, title FROM chats ORDER BY updated_at DESC, id DESC")?;
        stmt.query_map([], |row| {
            Ok(ChatSummary {
                id: row.get(0)?,
                title: row.get(1)?,
            })
        })?
        .collect()
    }

    pub fn create_chat(&self, title: &str) -> Result<i64> {
        self.conn.execute(
            "INSERT INTO chats (title, created_at, updated_at) VALUES (?1, ?2, ?2)",
            params![title, now()],
        )?;
        Ok(self.conn.last_insert_rowid())
    }

    /// A title chosen by the user; the chat won't be auto-titled after this.
    pub fn rename_chat(&self, id: i64, title: &str) -> Result<()> {
        self.conn.execute(
            "UPDATE chats SET title = ?2, auto_titled = 0 WHERE id = ?1",
            params![id, title],
        )?;
        Ok(())
    }

    /// A title generated by the AI; ignored if the user has renamed the chat.
    pub fn set_auto_title(&self, id: i64, title: &str) -> Result<()> {
        self.conn.execute(
            "UPDATE chats SET title = ?2 WHERE id = ?1 AND auto_titled = 1",
            params![id, title],
        )?;
        Ok(())
    }

    pub fn delete_chat(&self, id: i64) -> Result<()> {
        self.conn
            .execute("DELETE FROM chats WHERE id = ?1", params![id])?;
        Ok(())
    }

    pub fn messages(&self, chat_id: i64) -> Result<Vec<Message>> {
        let mut stmt = self
            .conn
            .prepare("SELECT role, content FROM chat_messages WHERE chat_id = ?1 ORDER BY id")?;
        let rows = stmt.query_map(params![chat_id], |row| {
            Ok((row.get::<_, String>(0)?, row.get::<_, String>(1)?))
        })?;
        let mut messages = Vec::new();
        for row in rows {
            let (role, content) = row?;
            if let Some(role) = Role::parse(&role) {
                messages.push(Message { role, content });
            }
        }
        Ok(messages)
    }

    pub fn add_message(&self, chat_id: i64, message: &Message) -> Result<()> {
        let now = now();
        self.conn.execute(
            "INSERT INTO chat_messages (chat_id, role, content, created_at) VALUES (?1, ?2, ?3, ?4)",
            params![chat_id, message.role.as_str(), message.content, now],
        )?;
        self.conn.execute(
            "UPDATE chats SET updated_at = ?2 WHERE id = ?1",
            params![chat_id, now],
        )?;
        Ok(())
    }
}

fn now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.as_secs() as i64)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn store() -> Store {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch("PRAGMA foreign_keys = ON;").unwrap();
        conn.execute_batch(SCHEMA).unwrap();
        Store { conn }
    }

    fn user(content: &str) -> Message {
        Message {
            role: Role::User,
            content: content.to_owned(),
        }
    }

    #[test]
    fn saves_and_loads_messages_in_order() {
        let store = store();
        let id = store.create_chat("Water").unwrap();
        store.add_message(id, &user("first")).unwrap();
        store
            .add_message(
                id,
                &Message {
                    role: Role::Assistant,
                    content: "second".to_owned(),
                },
            )
            .unwrap();
        let messages = store.messages(id).unwrap();
        assert_eq!(messages.len(), 2);
        assert_eq!(messages[0].content, "first");
        assert!(messages[1].role == Role::Assistant);
    }

    #[test]
    fn deleting_a_chat_deletes_its_messages() {
        let store = store();
        let id = store.create_chat("Fire").unwrap();
        store.add_message(id, &user("hi")).unwrap();
        store.delete_chat(id).unwrap();
        assert!(store.chats().unwrap().is_empty());
        assert!(store.messages(id).unwrap().is_empty());
    }

    #[test]
    fn auto_title_does_not_override_a_rename() {
        let store = store();
        let id = store.create_chat("placeholder").unwrap();
        store.set_auto_title(id, "AI title").unwrap();
        assert_eq!(store.chats().unwrap()[0].title, "AI title");
        store.rename_chat(id, "My title").unwrap();
        store.set_auto_title(id, "Another AI title").unwrap();
        assert_eq!(store.chats().unwrap()[0].title, "My title");
    }
}
